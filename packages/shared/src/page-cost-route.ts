import { imageAnchorsToAltText } from "./image-anchors.js";
import { isTableHeavy, PAGE_TABLE_ROUTING, type PageTable } from "./page-table-routing.js";

/*
 * Which cost path a PDF page takes, from structural facts about the page alone: the rule the offline estimator applies
 * to the pages it samples, and the rule the worker's own decisions are held to (worker parity test). No prices here.
 *
 * Production on the sandboxed PDF route (extract-markdown scan-fill, classify-route on the selective layout source):
 * - a page whose extracted text holds no letter or digit goes to the OCR engine (`scanFillPageNumbers`); the engine bills
 *   Rich for each page it reads words from, so a page with something drawn on it (an image or vector paths) is an
 *   `ocr-read`, and one with nothing drawn (`ocr-blank`) is OCR'd for no charge;
 * - every other page keeps its text layer (an OCR layer over a scan included: kept, not redone) and bills Fast;
 * - a page whose ruled grids are unknown, or whose grids make it table-heavy (`isTableHeavy`), takes the table path
 *   (`table`): layout-aware extraction, and a model read only when the extracted table proves unreliable, which only the
 *   extracted text can tell.
 */

/** Text a page holds for a "has words" test: image references and `<!-- page N -->` markers are not words read. */
export function ocrLedgerPageText(text: string | null | undefined): string {
  if (typeof text !== "string") return "";
  return imageAnchorsToAltText(text).replace(/<!--\s*page\s+\d+\s*-->/gi, "");
}

/** Whether a page's text holds a word for scan-fill: a letter or digit once image references and page markers are gone. */
export function ocrPageHasWords(text: string | null | undefined): boolean {
  return /[\p{L}\p{N}]/u.test(ocrLedgerPageText(text ?? ""));
}

/**
 * The pages scan-fill sends to the OCR engine (each one it reads with words bills Rich): every page whose winning text holds
 * no word. `split` is the page-aligned texts, or null when the text has no reliable page breaks (nothing is read).
 */
export function scanFillPageNumbers(split: readonly string[] | null): number[] | null {
  if (!split) return null;
  return split.map((text, index) => (ocrPageHasWords(text) ? 0 : index + 1)).filter((page) => page > 0);
}

/** Structural facts about one page, as counts. Null is unknown, never zero. */
export interface PageCostFacts {
  /** Words of the page's text layer, visible and invisible (an OCR layer counts). */
  words: number | null;
  /** Images drawn on the page (masks and stencils left out). */
  images: number | null;
  /** Vector path operations painted on the page. */
  vectorPaths: number | null;
  /** Ruled grids (rows, columns, coverage of the page); null when the rules are unknown. */
  grids: readonly PageTable[] | null;
  /** Share of the page the grids cover; null when unknown. */
  gridCoverage: number | null;
}

export const PAGE_COST_ROUTES = ["ocr-read", "ocr-blank", "table", "text", "unknown"] as const;
export type PageCostRoute = (typeof PAGE_COST_ROUTES)[number];

/**
 * The cost path of a page (see the module comment). `unknown` when the words are unknown, or when a page without words has
 * unknown drawing: unknown is never read as blank or as text.
 */
export function pageCostRoute(facts: PageCostFacts, tables: typeof PAGE_TABLE_ROUTING = PAGE_TABLE_ROUTING): PageCostRoute {
  if (facts.words === null || !Number.isFinite(facts.words)) return "unknown";
  if (facts.words <= 0) {
    if ((facts.images ?? 0) > 0 || (facts.vectorPaths ?? 0) > 0) return "ocr-read";
    return facts.images === null || facts.vectorPaths === null ? "unknown" : "ocr-blank";
  }
  if (facts.grids === null) return "table";
  return isTableHeavy(facts.grids, facts.gridCoverage, tables) ? "table" : "text";
}

/**
 * Cases spanning each branch of `pageCostRoute` and the table rule's edges, with the route the rule gives: the fixture the
 * estimator's Rust classifier is tested against (packages/estimate/page-cost-routes.json, regenerated by its test).
 */
export function buildPageCostRouteCases(): Array<{ facts: PageCostFacts; route: PageCostRoute }> {
  const rows = PAGE_TABLE_ROUTING.tableHeavyMinRows;
  const share = PAGE_TABLE_ROUTING.tableHeavyMinCoverage;
  const grid = (r: number, coverage: number | null = 0.1): PageTable => ({ rows: r, columns: 3, coverage });
  const base: PageCostFacts = { words: 120, images: 0, vectorPaths: 0, grids: [], gridCoverage: 0 };
  const facts: PageCostFacts[] = [
    base,
    { ...base, words: null },
    { ...base, words: 0 },
    { ...base, words: 0, images: 1 },
    { ...base, words: 0, vectorPaths: 40 },
    { ...base, words: 0, images: null },
    { ...base, words: 0, images: null, vectorPaths: 3 },
    { ...base, words: 0, vectorPaths: null },
    { ...base, words: 0, grids: null },
    { ...base, words: 1 },
    { ...base, words: 1, images: 4 },
    { ...base, grids: null, gridCoverage: null },
    { ...base, grids: [grid(rows - 1)], gridCoverage: 0.1 },
    { ...base, grids: [grid(rows)], gridCoverage: 0.1 },
    { ...base, grids: [grid(2), grid(3)], gridCoverage: share - 0.01 },
    { ...base, grids: [grid(2), grid(3)], gridCoverage: share },
    { ...base, grids: [grid(2, share)], gridCoverage: null },
    { ...base, grids: [grid(rows, null)], gridCoverage: null },
    { ...base, images: 12, vectorPaths: 900 },
    { ...base, images: null, vectorPaths: null, grids: [] },
  ];
  return facts.map((entry) => ({ facts: entry, route: pageCostRoute(entry) }));
}
