#!/usr/bin/env node
// Regenerates server/src/lib/public-suffix-data.ts from the Public Suffix List
// (ICANN and private sections). Run it monthly, and before a release that
// touches browser-key website checks; commit the result. Usage:
//   pnpm psl:update                                                # download from publicsuffix.org
//   node server/scripts/update-public-suffix-list.mjs ./list.dat   # use a downloaded copy
// The list is data only: rules are parsed, never evaluated. Commit the result.
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const out = new URL("../src/lib/public-suffix-data.ts", import.meta.url);

const text = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) })).text();
const version = /\/\/ VERSION: (\S+)/.exec(text)?.[1] ?? "unknown";
const commit = /\/\/ COMMIT: ([0-9a-f]+)/.exec(text)?.[1] ?? "unknown";

const rules = new Set();
for (const raw of text.split("\n")) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const exception = line.startsWith("!");
  const body = exception ? line.slice(1) : line;
  const labels = body.split(".").map((label) => (label === "*" ? "*" : /[^\x00-\x7f]/.test(label) ? domainToASCII(label) : label.toLowerCase()));
  if (labels.some((label) => !/^(?:\*|[a-z0-9-]+)$/.test(label))) throw new Error(`Unexpected rule: ${line}`);
  rules.add(`${exception ? "!" : ""}${labels.join(".")}`);
}
if (rules.size < 5_000) throw new Error(`Only ${rules.size} rules parsed; refusing to write a truncated list`);

const sorted = [...rules].sort();
writeFileSync(out, `// Generated by server/scripts/update-public-suffix-list.mjs. Do not edit.
// Public Suffix List ${version} (commit ${commit}), ICANN and private sections, ${sorted.length} rules.
// Source: ${SOURCE}
// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0.
// If a copy of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.

export const PUBLIC_SUFFIX_LIST_VERSION = ${JSON.stringify(version)};

/** One rule per line: \`com\`, \`*.ck\` (wildcard), \`!www.ck\` (exception), labels in ASCII (punycode). */
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify(sorted.join("\n"))};
`);
console.log(`Wrote ${sorted.length} rules (${version}) to ${out.pathname}`);
