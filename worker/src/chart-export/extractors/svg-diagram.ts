import type { DiagramSpec } from "@docslurp/shared/chart-export";

import { finalizeDiagram } from "./spec-utils.js";
import { parseTransform, apply, type Matrix, IDENTITY, multiply } from "./svg-path.js";
import { cleanLabel } from "./text.js";
import { descendants, elementChildren, firstChild, textContent, type XmlElement } from "./xml.js";

/*
 * Diagrams from SVG, only where the generator's markup names nodes and edges: Mermaid flowcharts (`flowchart-*` node
 * ids, `L_A_B_0` / `LS-A LE-B` edge ids) and Graphviz (`class="node"` / `class="edge"` with `<title>a&#45;&gt;b</title>`).
 * Anything else returns null; layout-only diagram recovery is left to the model rungs.
 */

type Node = DiagramSpec["nodes"][number];
type Edge = DiagramSpec["edges"][number];
type Shape = Node["shape"];

export interface SvgDiagramResult { spec: DiagramSpec | null; generator: "mermaid" | "graphviz"; confidence: number; reason: string | null }

const classes = (el: XmlElement) => (el.attrs.class ?? "").split(/\s+/).filter(Boolean);

function allElements(root: XmlElement): XmlElement[] {
  const out: XmlElement[] = [];
  const stack = [root];
  while (stack.length) {
    const cur = stack.pop()!;
    out.push(cur);
    for (let k = cur.children.length - 1; k >= 0; k--) { const c = cur.children[k]!; if (c.type === "element") stack.push(c); }
  }
  return out;
}

/** Ids safe for any text format: [A-Za-z0-9_-], ≤64 chars, unique. */
function idMaker() {
  const used = new Map<string, string>();
  const taken = new Set<string>();
  return (raw: string): string => {
    const prior = used.get(raw);
    if (prior) return prior;
    let base = raw.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 56) || "n";
    if (/^[0-9-]/.test(base)) base = `n${base}`.slice(0, 56);
    let id = base;
    for (let k = 2; taken.has(id); k++) id = `${base}_${k}`;
    taken.add(id);
    used.set(raw, id);
    return id;
  };
}

function direction(centers: Map<string, [number, number]>, edges: Array<{ from: string; to: string }>): DiagramSpec["direction"] {
  let dx = 0, dy = 0;
  for (const e of edges) {
    const a = centers.get(e.from), b = centers.get(e.to);
    if (!a || !b) continue;
    dx += b[0] - a[0]; dy += b[1] - a[1];
  }
  if (Math.abs(dx) > Math.abs(dy)) return dx >= 0 ? "LR" : "RL";
  return dy >= 0 ? "TB" : "BT";
}

function shapeOf(g: XmlElement): Shape {
  for (const c of elementChildren(g)) {
    if (c.local === "g") { const s = shapeOf(c); if (s !== "other") return s; continue; }
    if (c.local === "rect") return Number(c.attrs.rx ?? 0) > 0 ? "rounded" : "box";
    if (c.local === "circle") return "circle";
    if (c.local === "ellipse") return Math.abs(Number(c.attrs.rx) - Number(c.attrs.ry)) < 0.5 ? "circle" : "rounded";
    if (c.local === "polygon") {
      const nums = (c.attrs.points ?? "").match(/[-+]?(?:\d+\.?\d*|\.\d+)/g)?.map(Number) ?? [];
      const pts: Array<[number, number]> = [];
      for (let k = 0; k + 1 < nums.length; k += 2) pts.push([nums[k]!, nums[k + 1]!]);
      if (pts.length > 1 && pts[0]![0] === pts[pts.length - 1]![0] && pts[0]![1] === pts[pts.length - 1]![1]) pts.pop();
      if (pts.length === 4) {
        const sharesAxis = pts.some((p, k) => { const q = pts[(k + 1) % 4]!; return Math.abs(p[0] - q[0]) < 0.5 || Math.abs(p[1] - q[1]) < 0.5; });
        return sharesAxis ? "box" : "diamond";
      }
      return "other";
    }
    if (c.local === "path" && /cylinder/.test(c.attrs.class ?? "")) return "cylinder";
  }
  return "other";
}

function labelOf(g: XmlElement): string {
  const fo = descendants(g, "foreignObject").map((f) => textContent(f)).join(" ");
  if (fo.trim()) return cleanLabel(fo);
  return cleanLabel(descendants(g, "text").map((t) => textContent(t)).join(" "));
}

function translateOf(el: XmlElement, parent: Matrix = IDENTITY): [number, number] {
  const m = multiply(parent, parseTransform(el.attrs.transform) ?? IDENTITY);
  return apply(m, 0, 0);
}

export function detectDiagramGenerator(root: XmlElement, signatures: string): "mermaid" | "graphviz" | null {
  if (/Generated by graphviz/i.test(signatures)) return "graphviz";
  const svg = root.local === "svg" ? root : elementChildren(root).find((c) => c.local === "svg");
  if (!svg) return null;
  const role = svg.attrs["aria-roledescription"] ?? "";
  if (/^flowchart/.test(role) || (classes(svg).includes("flowchart") && /^mermaid/.test(svg.attrs.id ?? ""))) return "mermaid";
  if (/^mermaid/.test(svg.attrs.id ?? "") && allElements(svg).some((e) => classes(e).includes("edgePath") || classes(e).includes("flowchart-link"))) return "mermaid";
  return null;
}

export function mermaidFlowchart(root: XmlElement): SvgDiagramResult {
  const els = allElements(root);
  const makeId = idMaker();
  const nodes: Node[] = [];
  const rawIds: string[] = [];
  const centers = new Map<string, [number, number]>();
  for (const g of els) {
    if (g.local !== "g" || !classes(g).includes("node")) continue;
    const m = /^(?:[A-Za-z0-9_-]*?-)?flowchart-(.+)-\d+$/.exec(g.attrs.id ?? "");
    if (!m) continue;
    const raw = m[1]!;
    if (rawIds.includes(raw)) continue;
    rawIds.push(raw);
    const id = makeId(raw);
    nodes.push({ id, label: labelOf(g) || raw, shape: shapeOf(g), group: null });
    centers.set(id, translateOf(g));
  }
  if (!nodes.length) return { spec: null, generator: "mermaid", confidence: 0, reason: "mermaid-not-flowchart" };
  const split = (body: string, sep: string): [string, string] | null => {
    const parts = body.split(sep);
    for (let k = 1; k < parts.length; k++) {
      const a = parts.slice(0, k).join(sep), b = parts.slice(k).join(sep);
      if (rawIds.includes(a) && rawIds.includes(b)) return [a, b];
    }
    return null;
  };
  const edgeLabels = new Map<string, string>();
  for (const g of els) {
    if (g.local === "g" && classes(g).includes("label") && g.attrs["data-id"]) edgeLabels.set(g.attrs["data-id"], labelOf(g));
  }
  const edges: Edge[] = [];
  let unresolved = 0;
  for (const el of els) {
    const cls = classes(el);
    let pair: [string, string] | null = null;
    let key = "";
    let styleSource = el;
    if (el.local === "path" && (cls.includes("flowchart-link") || el.attrs["data-edge"] === "true")) {
      key = el.attrs["data-id"] ?? el.attrs.id ?? "";
      const m = /^L[_-](.+)[_-]\d+$/.exec(key);
      pair = m ? split(m[1]!, "_") ?? split(m[1]!, "-") : null;
    } else if (el.local === "g" && cls.includes("edgePath")) {
      const ls = cls.find((c) => c.startsWith("LS-"))?.slice(3);
      const le = cls.find((c) => c.startsWith("LE-"))?.slice(3);
      pair = ls && le && rawIds.includes(ls) && rawIds.includes(le) ? [ls, le] : null;
      key = el.attrs.id ?? "";
      styleSource = firstChild(el, "path") ?? el;
    } else continue;
    if (!pair) { unresolved++; continue; }
    const sc = classes(styleSource).join(" ");
    edges.push({
      from: makeId(pair[0]), to: makeId(pair[1]),
      label: edgeLabels.get(key) || null,
      style: /dotted|dashed/.test(sc) ? "dashed" : /edge-thickness-thick|(?:^| )thick(?: |$)/.test(sc) ? "thick" : "solid",
      directed: !!(styleSource.attrs["marker-end"] || styleSource.attrs["marker-start"]),
    });
  }
  const spec = finalizeDiagram({ diagramType: "flowchart", title: null, direction: direction(centers, edges), nodes, edges });
  const total = edges.length + unresolved;
  return { spec, generator: "mermaid", confidence: spec ? Math.max(0.5, 0.95 - (total ? 0.4 * (unresolved / total) : 0)) : 0, reason: unresolved ? "edges-unresolved" : null };
}

export function graphvizDiagram(root: XmlElement): SvgDiagramResult {
  const els = allElements(root);
  const makeId = idMaker();
  const nodes: Node[] = [];
  const centers = new Map<string, [number, number]>();
  const known = new Set<string>();
  const graphG = els.find((e) => e.local === "g" && classes(e).includes("graph"));
  const graphTitle = graphG ? cleanLabel(textContent(firstChild(graphG, "title"))) : "";
  const clusters: Array<{ id: string; label: string; box: [number, number, number, number] }> = [];
  const shapeCenter = (g: XmlElement): [number, number] | null => {
    for (const c of elementChildren(g)) {
      if (c.local === "ellipse" || c.local === "circle") return [Number(c.attrs.cx) || 0, Number(c.attrs.cy) || 0];
      if (c.local === "polygon" || c.local === "path") {
        const nums = ((c.local === "polygon" ? c.attrs.points : c.attrs.d) ?? "").match(/[-+]?(?:\d+\.?\d*|\.\d+)/g)?.slice(0, 400).map(Number) ?? [];
        if (nums.length >= 2) { let sx = 0, sy = 0, n = 0; for (let k = 0; k + 1 < nums.length; k += 2) { sx += nums[k]!; sy += nums[k + 1]!; n++; } return [sx / n, sy / n]; }
      }
    }
    return null;
  };
  for (const g of els) {
    if (g.local !== "g" || !classes(g).includes("cluster")) continue;
    const poly = firstChild(g, "polygon") ?? firstChild(g, "path");
    const nums = ((poly?.local === "polygon" ? poly.attrs.points : poly?.attrs.d) ?? "").match(/[-+]?(?:\d+\.?\d*|\.\d+)/g)?.slice(0, 400).map(Number) ?? [];
    const xs = nums.filter((_, k) => k % 2 === 0), ys = nums.filter((_, k) => k % 2 === 1);
    if (!xs.length) continue;
    const title = cleanLabel(textContent(firstChild(g, "title")));
    clusters.push({ id: makeId(`cluster:${title}`), label: cleanLabel(descendants(g, "text").map((t) => textContent(t)).join(" ")) || title, box: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)] });
  }
  for (const g of els) {
    if (g.local !== "g" || !classes(g).includes("node")) continue;
    const raw = textContent(firstChild(g, "title")).trim();
    if (!raw || known.has(raw)) continue;
    known.add(raw);
    const id = makeId(raw);
    const c = shapeCenter(g);
    let group: string | null = null;
    if (c) {
      centers.set(id, c);
      const containing = clusters.filter((k) => c[0] >= k.box[0] && c[0] <= k.box[2] && c[1] >= k.box[1] && c[1] <= k.box[3])
        .sort((a, b) => (a.box[2] - a.box[0]) * (a.box[3] - a.box[1]) - (b.box[2] - b.box[0]) * (b.box[3] - b.box[1]));
      group = containing[0]?.id ?? null;
    }
    nodes.push({ id, label: cleanLabel(descendants(g, "text").map((t) => textContent(t)).join(" ")) || cleanLabel(raw), shape: shapeOf(g), group });
  }
  if (!nodes.length) return { spec: null, generator: "graphviz", confidence: 0, reason: "graphviz-no-nodes" };
  const edges: Edge[] = [];
  let unresolved = 0;
  for (const g of els) {
    if (g.local !== "g" || !classes(g).includes("edge")) continue;
    const title = textContent(firstChild(g, "title")).trim();
    const directed = title.includes("->");
    const parts = title.split(directed ? "->" : "--");
    const strip = (s: string) => { const t = s.trim(); return known.has(t) ? t : t.replace(/:[^:]*$/, ""); };
    if (parts.length !== 2 || !known.has(strip(parts[0]!)) || !known.has(strip(parts[1]!))) { unresolved++; continue; }
    const path = firstChild(g, "path");
    const dash = path?.attrs["stroke-dasharray"] ?? /stroke-dasharray/.test(path?.attrs.style ?? "") ? "x" : "";
    const width = Number(path?.attrs["stroke-width"] ?? 1);
    edges.push({ from: makeId(strip(parts[0]!)), to: makeId(strip(parts[1]!)), label: cleanLabel(descendants(g, "text").map((t) => textContent(t)).join(" ")) || null, style: dash ? "dashed" : width >= 2 ? "thick" : "solid", directed });
  }
  const spec = finalizeDiagram({
    diagramType: "flowchart",
    title: graphTitle && !/^(G|%\d+|graph\d*)$/i.test(graphTitle) ? graphTitle : null,
    direction: direction(centers, edges),
    nodes,
    edges,
    groups: clusters.filter((k) => nodes.some((n) => n.group === k.id)).map((k) => ({ id: k.id, label: k.label })),
  });
  const total = edges.length + unresolved;
  return { spec, generator: "graphviz", confidence: spec ? 0.95 - (total ? 0.4 * (unresolved / total) : 0) : 0, reason: unresolved ? "edges-unresolved" : null };
}
